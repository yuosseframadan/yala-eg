  update public.shop_orders set total=coalesce((select sum(price*qty) from public.shop_order_items where order_id=oid),0)+shipping where id=oid $$;

-- حماية المنتجات: حد الباقة + ملء اسم/تليفون التاجر + منع خصم غلط
create or replace function public.products_guard() returns trigger language plpgsql security definer set search_path=public as $$
declare m public.merchants; c int;
begin
  if new.merchant_id is not null then
    select * into m from public.merchants where id=new.merchant_id;
    if m.id is null then raise exception 'تاجر غير موجود'; end if;
    new.merchant_name:=m.name; new.seller:=m.name; new.merchant_phone:=m.phone;
    if tg_op='INSERT' and not public.is_admin() then
      if not m.is_active then raise exception 'حساب البائع موقوف'; end if;
      if m.plan_end is not null and m.plan_end<now() then raise exception 'الباقة منتهية، جدّد اشتراكك'; end if;
      select count(*) into c from public.products where merchant_id=new.merchant_id;
      if c>=public.plan_limit(m.plan) then raise exception 'وصلت للحد الأقصى لمنتجات باقتك'; end if;
    end if;
  end if;
  if new.old_price is not null and new.old_price<=new.price then new.old_price:=null; end if;
  return new;
end $$;
drop trigger if exists products_guard_t on public.products;
create trigger products_guard_t before insert or update on public.products for each row execute function public.products_guard();

-- 4) تسجيل الطلب: محل واحد في الأوردر الواحد، الأسعار من قاعدة البيانات وبتتثبت، والمخزون بيتخصم فوراً
create or replace function public.place_order(p_name text,p_phone text,p_address text,p_note text,p_ship numeric,p_items jsonb)
returns bigint language plpgsql security definer set search_path=public as $$
declare oid bigint; it jsonb; pr public.products; q int; tot numeric:=0; n int:=0; fm bigint:=null;
begin
  if (select count(*) from public.shop_orders where phone=left(coalesce(p_phone,''),20) and created_at>now()-interval '1 hour')>=5 then raise exception 'طلبات كتير في وقت قصير'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>50 then raise exception 'سلة غير صالحة'; end if;
  insert into public.shop_orders(name,phone,address,note,shipping) values(left(coalesce(p_name,''),100),left(coalesce(p_phone,''),20),left(coalesce(p_address,''),300),left(coalesce(p_note,''),300),least(greatest(coalesce(p_ship,20),0),500)) returning id into oid;
  for it in select * from jsonb_array_elements(p_items) loop
    select * into pr from public.products where id=(it->>'id')::bigint for update;
    if pr.id is null or not public.merchant_visible(pr.merchant_id) then continue; end if;
    if n>0 and coalesce(pr.merchant_id,0)<>coalesce(fm,0) then raise exception 'لازم الطلب يكون من محل واحد في الأوردر الواحد. كمّل طلب المحل الحالي أولاً أو فضّي السلة'; end if;
    if n=0 then fm:=pr.merchant_id; end if;
    q:=least(greatest(coalesce((it->>'qty')::int,1),1),100);
    if coalesce(pr.stock,0)<q then raise exception 'الكمية المتاحة من "%" غير كافية (المتاح %)', pr.name, coalesce(pr.stock,0); end if;
    update public.products set stock=stock-q where id=pr.id;
    insert into public.shop_order_items(order_id,product_id,merchant_id,name,price,qty) values(oid,pr.id,pr.merchant_id,pr.name,pr.price,q);
    tot:=tot+pr.price*q; n:=n+1;
  end loop;
  if n=0 then raise exception 'مفيش منتجات صالحة'; end if;
  update public.shop_orders set total=tot+shipping where id=oid;
  return oid;
end $$;

-- 5) تجهيز الأوردر: البائع يضغط "جاهز للتسليم" فينزل للطيارين فوراً بتوصيل مبدئي 20 (المالك يعدّله). المالك له نفس الصلاحية على كل الأوردرات.
create or replace function public.mark_ready(p_oid bigint, p_val boolean default true) returns void language plpgsql security definer set search_path=public as $$
declare o public.shop_orders; mid bigint;
begin
  select * into o from public.shop_orders where id=p_oid;
  if o.id is null then raise exception 'الأوردر مش موجود'; end if;
  if o.status='cancelled' or o.cancel_req then raise exception 'الأوردر ملغي أو عليه طلب إلغاء'; end if;
  if o.rider_status<>'open' then raise exception 'الأوردر مع طيار أو اتسلم'; end if;
  if public.is_admin() then update public.shop_order_items set ready=p_val where order_id=p_oid;
  else
    mid:=public.my_mid();
    if mid is null or not exists(select 1 from public.shop_order_items where order_id=p_oid and merchant_id=mid) then raise exception 'مش مصرح'; end if;
    update public.shop_order_items set ready=p_val where order_id=p_oid and merchant_id=mid;
  end if;
end $$;

-- البائع يطلب تقليل كمية صنف (0 = شيل الصنف). مبيتنفذش ولا بيتخصم من حسابه غير بعد موافقة المالك.
create or replace function public.request_item_change(p_id bigint, p_qty int) returns void language plpgsql security definer set search_path=public as $$
declare it public.shop_order_items; o public.shop_orders; mid bigint;
begin
  select * into it from public.shop_order_items where id=p_id;
  if it.id is null then raise exception 'الصنف مش موجود'; end if;
  mid:=public.my_mid();
  if mid is null or it.merchant_id is distinct from mid then raise exception 'مش مصرح'; end if;
  select * into o from public.shop_orders where id=it.order_id;
  if o.status='cancelled' or o.rider_status<>'open' then raise exception 'مينفعش التعديل: الأوردر مع طيار أو اتسلم أو ملغي'; end if;
  if p_qty is null or p_qty<0 or p_qty>it.qty then raise exception 'الكمية لازم تكون من 0 لحد %', it.qty; end if;
  if p_qty=it.qty then update public.shop_order_items set req_qty=null where id=p_id;
  else update public.shop_order_items set req_qty=p_qty where id=p_id; update public.shop_order_items set ready=false where order_id=it.order_id; end if;
end $$;

-- البائع يضغط "لم يتم الأوردر": مجرد طلب إلغاء، والمالك هو اللي يأكده. بعد ما الطيار يسلّم مفيش إلغاء من البائع نهائياً.
create or replace function public.request_cancel(p_oid bigint, p_val boolean default true) returns void language plpgsql security definer set search_path=public as $$
declare o public.shop_orders; mid bigint;
begin
  select * into o from public.shop_orders where id=p_oid;
  if o.id is null then raise exception 'الأوردر مش موجود'; end if;
  if o.rider_status='delivered' then raise exception 'الأوردر اتسلّم للعميل، مينفعش البائع يلغيه'; end if;
  if o.status='cancelled' then raise exception 'الأوردر ملغي بالفعل'; end if;
  mid:=public.my_mid();
  if mid is null or not exists(select 1 from public.shop_order_items where order_id=p_oid and merchant_id=mid) then raise exception 'مش مصرح'; end if;
  update public.shop_orders set cancel_req=p_val where id=p_oid;
  update public.shop_order_items set cxl=p_val where order_id=p_oid;
  if p_val then update public.shop_order_items set ready=false where order_id=p_oid; end if;
end $$;

-- إلغاء الأوردر فعلياً (داخلية): يشيله من الطيار، يرجّع المخزون، ويصفّر الحسابات (مفيش عمولة على البائع ولا على الطيار)
create or replace function public.cancel_core(p_oid bigint, p_restock boolean) returns void language plpgsql security definer set search_path=public as $$
begin
  if p_restock then
    update public.products p set stock=p.stock+i.qty from public.shop_order_items i where i.order_id=p_oid and i.product_id=p.id and not i.cancelled;
  end if;
  update public.shop_order_items set cancelled=true, cancelled_at=now(), req_qty=null, ready=false, cxl=false, stage='cancelled' where order_id=p_oid and not cancelled;
  update public.shop_orders set status='cancelled', cancel_req=false, cancelled_at=now(), rider_id=null, rider_status='cancelled' where id=p_oid;
end $$;
revoke execute on function public.cancel_core(bigint, boolean) from public, anon, authenticated;

create or replace function public.admin_cancel_order(p_oid bigint, p_restock boolean default true) returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  if exists(select 1 from public.shop_orders where id=p_oid and status='cancelled') then return; end if;
  perform public.cancel_core(p_oid, p_restock);
end $$;
create or replace function public.resolve_cancel(p_oid bigint, p_approve boolean) returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  if p_approve then perform public.cancel_core(p_oid, true);
  else update public.shop_orders set cancel_req=false where id=p_oid; update public.shop_order_items set cxl=false where order_id=p_oid; end if;
end $$;
create or replace function public.resolve_item_change(p_id bigint, p_approve boolean) returns void language plpgsql security definer set search_path=public as $$
declare it public.shop_order_items; o public.shop_orders; d int;
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  select * into it from public.shop_order_items where id=p_id;
  if it.id is null or it.req_qty is null then return; end if;
  select * into o from public.shop_orders where id=it.order_id;
  if o.rider_status<>'open' or o.status='cancelled' then raise exception 'الأوردر مع طيار أو ملغي'; end if;
  if not p_approve then update public.shop_order_items set req_qty=null where id=p_id; return; end if;
  d:=it.qty-it.req_qty;
  if d>0 and it.product_id is not null then update public.products set stock=stock+d where id=it.product_id; end if;
  if it.req_qty=0 then delete from public.shop_order_items where id=p_id; else update public.shop_order_items set qty=it.req_qty, req_qty=null where id=p_id; end if;
  if not exists(select 1 from public.shop_order_items where order_id=it.order_id) then perform public.cancel_core(it.order_id,false); else perform public.recalc_order(it.order_id); end if;
end $$;

-- المالك يعدّل كمية/سعر صنف أو سعر التوصيل قبل ما طيار ياخد الأوردر
create or replace function public.adjust_item(p_id bigint, p_qty int, p_price numeric) returns void language plpgsql security definer set search_path=public as $$
declare it public.shop_order_items; o public.shop_orders; d int;
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  select * into it from public.shop_order_items where id=p_id;
  if it.id is null then raise exception 'الصنف مش موجود'; end if;
  select * into o from public.shop_orders where id=it.order_id;
  if o.status='cancelled' or o.rider_status<>'open' then raise exception 'الأوردر مع طيار أو اتسلم أو ملغي'; end if;
  if p_qty is null or p_qty<0 or p_qty>it.qty then raise exception 'الكمية لازم تكون من 0 لحد %', it.qty; end if;
  if p_price is null or p_price<0 then raise exception 'سعر غير صالح'; end if;
  d:=it.qty-p_qty;
  if d>0 and it.product_id is not null then update public.products set stock=stock+d where id=it.product_id; end if;
  if p_qty=0 then delete from public.shop_order_items where id=p_id;
  else update public.shop_order_items set qty=p_qty, price=p_price, req_qty=null where id=p_id; end if;
  if not exists(select 1 from public.shop_order_items where order_id=it.order_id) then perform public.cancel_core(it.order_id,false); else perform public.recalc_order(it.order_id); end if;
end $$;
create or replace function public.set_shipping(p_oid bigint, p_ship numeric) returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  if p_ship is null or p_ship<0 or p_ship>500 then raise exception 'سعر توصيل غير صالح'; end if;
  if not exists(select 1 from public.shop_orders where id=p_oid and rider_status='open' and status<>'cancelled') then raise exception 'مينفعش تعديل التوصيل: الأوردر مع طيار أو ملغي'; end if;
  update public.shop_orders set shipping=p_ship where id=p_oid;
  perform public.recalc_order(p_oid);
end $$;
create or replace function public.remove_order(p_id bigint, p_restock boolean) returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'مش مصرح'; end if;
  if p_restock then update public.products p set stock=p.stock+i.qty from public.shop_order_items i where i.order_id=p_id and i.product_id=p.id and not i.cancelled and not i.delivered; end if;
  delete from public.shop_orders where id=p_id;
end $$;

-- الأوردر جاهز للطيارين: كل أصنافه جاهزة، مفيش طلب تعديل/إلغاء معلّق، ومش ملغي
create or replace function public.order_ready(oid bigint) returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.shop_orders o where o.id=oid and o.status<>'cancelled' and not o.cancel_req)
     and exists(select 1 from public.shop_order_items where order_id=oid)
     and not exists(select 1 from public.shop_order_items where order_id=oid and (not ready or req_qty is not null)) $$;

-- 6) الطيار (بدون بيانات العميل لحد ما يستلم الأوردر من المحل)
create or replace function public.rider_orders() returns jsonb language plpgsql stable security definer set search_path=public as $$
declare r public.riders; res jsonb;
begin
  select * into r from public.riders where user_id=auth.uid() and is_active;
  if r.id is null then raise exception 'مش حساب طيار'; end if;
  select coalesce(jsonb_agg(x order by (x->>'id')::bigint desc),'[]'::jsonb) into res from (
    select jsonb_build_object('id',o.id,'status',o.rider_status,'mine',(o.rider_id=r.id),'shipping',o.shipping,'total',o.total,'created_at',o.created_at,
      'accepted_at',case when o.rider_id=r.id then o.accepted_at end,'picked_at',case when o.rider_id=r.id then o.picked_at end,'delivered_at',case when o.rider_id=r.id then o.delivered_at end,
      'name',case when o.rider_id=r.id and o.rider_status in ('picked','delivered') then o.name end,
      'phone',case when o.rider_id=r.id and o.rider_status in ('picked','delivered') then o.phone end,
      'address',case when o.rider_id=r.id and o.rider_status in ('picked','delivered') then o.address end,
      'note',case when o.rider_id=r.id and o.rider_status in ('picked','delivered') then o.note end,
      'items',case when o.rider_id is null or o.rider_id=r.id then
        (select coalesce(jsonb_agg(jsonb_build_object('name',i.name,'qty',i.qty,'price',i.price,'shop',coalesce(m.name,'yala-eg'),'shop_address',m.address,'shop_phone',m.phone)),'[]'::jsonb)
           from public.shop_order_items i left join public.merchants m on m.id=i.merchant_id where i.order_id=o.id) else '[]'::jsonb end) as x
    from public.shop_orders o
    where o.status<>'cancelled' and (
      o.rider_id=r.id
      or (o.rider_id is null and o.rider_status='open' and public.order_ready(o.id)
          and (r.merchant_id is null or not exists(select 1 from public.shop_order_items i where i.order_id=o.id and i.merchant_id is distinct from r.merchant_id)))
      or (o.rider_id is not null and o.rider_id<>r.id and o.rider_status in ('accepted','picked') and o.accepted_at>now()-interval '1 day'))
    order by o.id desc limit 100) t;
  return res;
end $$;

-- أخذ الأوردر: تحديث واحد ذري بشرط rider_id is null، فأول طيار يوصل للسيرفر بس هو اللي ياخده والتاني بيرجعله false
create or replace function public.rider_step(p_id bigint, p_step text) returns boolean language plpgsql security definer set search_path=public as $$
declare r public.riders; n int;
begin
  select * into r from public.riders where user_id=auth.uid() and is_active;
  if r.id is null then raise exception 'مش حساب طيار'; end if;
  if p_step='accept' then
    if exists(select 1 from public.shop_orders where rider_id=r.id and rider_status in ('accepted','picked')) then raise exception 'سلّم أوردرك الحالي الأول'; end if;
    update public.shop_orders o set rider_id=r.id, accepted_at=now(), rider_status='accepted'
     where o.id=p_id and o.rider_id is null and o.rider_status='open' and o.status<>'cancelled' and public.order_ready(o.id)
       and (r.merchant_id is null or not exists(select 1 from public.shop_order_items i where i.order_id=o.id and i.merchant_id is distinct from r.merchant_id));
    get diagnostics n = row_count;
    if n>0 then update public.shop_order_items set stage='accepted' where order_id=p_id; end if;
    return n>0;
  elsif p_step='pick' then
    update public.shop_orders set picked_at=now(), rider_status='picked' where id=p_id and rider_id=r.id and rider_status='accepted' and status<>'cancelled';
    get diagnostics n = row_count;
    if n>0 then update public.shop_order_items set stage='picked' where order_id=p_id; end if;
    return n>0;
  elsif p_step='deliver' then
    update public.shop_orders set delivered_at=now(), rider_status='delivered', cancel_req=false where id=p_id and rider_id=r.id and rider_status='picked' and status<>'cancelled';
    get diagnostics n = row_count;
    if n>0 then update public.shop_order_items set stage='delivered', delivered=true, delivered_at=now(), cxl=false where order_id=p_id; end if;
    return n>0;
  end if;
  raise exception 'خطوة غير معروفة';
end $$;

create or replace function public.rider_summary() returns jsonb language plpgsql stable security definer set search_path=public as $$
declare r public.riders; fees numeric; n int; paid numeric;
begin
  select * into r from public.riders where user_id=auth.uid() and is_active;
  if r.id is null then raise exception 'مش حساب طيار'; end if;
  select coalesce(sum(shipping),0), count(*) into fees, n from public.shop_orders where rider_id=r.id and rider_status='delivered' and status<>'cancelled';
  select coalesce(sum(amount),0) into paid from public.rider_payments where rider_id=r.id;
  return jsonb_build_object('count',n,'fees',fees,'share',fees*0.15,'net',fees*0.85,'paid',paid,'left',fees*0.15-paid,
    'rating',(select round(avg(stars)::numeric,1) from public.rider_reviews where rider_id=r.id),'reviews',(select count(*) from public.rider_reviews where rider_id=r.id));
end $$;

-- 8) تتبع الطلب والتقييم والإحصائيات (متاحة للزوار، بتطلّع بيانات محدودة بس)
create or replace function public.track_order(p_id bigint default null, p_phone text default null) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare ph text:=regexp_replace(coalesce(p_phone,''),'\D','','g'); res jsonb;
begin
  if p_id is null and length(ph)<8 then return '[]'::jsonb; end if;
  select coalesce(jsonb_agg(x order by (x->>'id')::bigint desc),'[]'::jsonb) into res from (
    select jsonb_build_object('id',o.id,
      'stage',case when o.status='cancelled' then 'cancelled' when o.rider_status='delivered' then 'done' when o.rider_status='picked' then 'way' when o.rider_id is not null or public.order_ready(o.id) then 'prep' else 'review' end,
      'created_at',o.created_at,'delivered_at',o.delivered_at,'total',o.total,'shipping',o.shipping,'rated',o.rated,
      'items',(select coalesce(jsonb_agg(jsonb_build_object('product_id',i.product_id,'name',i.name,'qty',i.qty,'price',i.price)),'[]'::jsonb) from public.shop_order_items i where i.order_id=o.id)) as x
    from public.shop_orders o
    where (p_id is not null and o.id=p_id) or (p_id is null and regexp_replace(coalesce(o.phone,''),'\D','','g')=ph)
    order by o.id desc limit 10) t;
  return res;
end $$;

create or replace function public.rate_order(p_id bigint, p_phone text, p_rider int, p_items jsonb) returns void language plpgsql security definer set search_path=public as $$
declare o public.shop_orders; it jsonb; s int;
begin
  select * into o from public.shop_orders where id=p_id;
  if o.id is null or regexp_replace(coalesce(o.phone,''),'\D','','g')<>regexp_replace(coalesce(p_phone,''),'\D','','g') then raise exception 'بيانات الأوردر غير صحيحة'; end if;
  if o.rider_status<>'delivered' then raise exception 'الأوردر لسه متسلمش'; end if;
  if o.rated then raise exception 'الأوردر اتقيّم قبل كده'; end if;
  for it in select * from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) loop
    s:=least(greatest(coalesce((it->>'stars')::int,0),0),5);
    if s>=1 and exists(select 1 from public.shop_order_items where order_id=p_id and product_id=(it->>'product_id')::bigint) then
      insert into public.product_reviews(product_id,order_id,stars) values((it->>'product_id')::bigint,p_id,s) on conflict (order_id,product_id) do nothing;
    end if;
  end loop;
  if o.rider_id is not null and p_rider between 1 and 5 then insert into public.rider_reviews(order_id,rider_id,stars) values(p_id,o.rider_id,p_rider) on conflict (order_id) do nothing; end if;
  update public.shop_orders set rated=true where id=p_id;
end $$;

create or replace function public.store_stats() returns jsonb language sql stable security definer set search_path=public as $$
  select jsonb_build_object(
    'sold',coalesce((select jsonb_object_agg(product_id::text,q) from (select product_id,sum(qty) q from public.shop_order_items where delivered and not cancelled and product_id is not null group by product_id) a),'{}'::jsonb),
    'rating',coalesce((select jsonb_object_agg(product_id::text,jsonb_build_object('avg',av,'cnt',c)) from (select product_id,round(avg(stars)::numeric,1) av,count(*) c from public.product_reviews group by product_id) b),'{}'::jsonb)) $$;

create or replace function public.save_push(p_endpoint text, p_p256dh text, p_auth text, p_cart boolean) returns void language sql security definer set search_path=public as $$
  insert into public.push_subs(endpoint,p256dh,auth,cart_at,cart_reminded) values(p_endpoint,p_p256dh,p_auth,case when p_cart then now() end,false)
  on conflict (endpoint) do update set p256dh=excluded.p256dh, auth=excluded.auth, cart_at=case when p_cart then now() end, cart_reminded=false $$;

