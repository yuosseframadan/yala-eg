create table if not exists public.shop_orders (id bigint generated by default as identity primary key, name text, phone text, address text, note text,
  shipping numeric not null default 0, total numeric not null default 0, status text not null default 'new', created_at timestamptz default now());
create table if not exists public.shop_order_items (id bigint generated by default as identity primary key,
  order_id bigint not null references public.shop_orders(id) on delete cascade, product_id bigint, merchant_id bigint, name text,
  price numeric not null, qty int not null default 1, is_digital boolean not null default false, status text not null default 'new', created_at timestamptz default now());
create table if not exists public.shop_payments (id bigint generated by default as identity primary key, merchant_id bigint not null references public.merchants(id) on delete cascade,
  amount numeric not null, note text, created_at timestamptz default now());

-- دوال مساعدة
create or replace function public.is_admin() returns boolean language sql stable as $$ select auth.uid() = '57961390-b0f4-4721-9b55-acaa81c946fa'::uuid $$;
create or replace function public.my_mid() returns bigint language sql stable security definer set search_path=public as $$ select id from public.merchants where user_id=auth.uid() and is_active limit 1 $$;
create or replace function public.merchant_visible(mid bigint) returns boolean language sql stable security definer set search_path=public as $$
  select mid is null or exists(select 1 from public.merchants m where m.id=mid and m.is_active) $$;
create or replace function public.plan_limit(p text) returns int language sql immutable as $$
  select case p when 'commission' then 15 when 'silver' then 35 when 'gold' then 50 when 'business' then 100 else 1000000 end $$;
create or replace function public.login_email(p text) returns text language sql stable security definer set search_path=public as $$
  select email from public.merchants where lower(email)=lower(p)
   or (length(regexp_replace(p,'\D','','g'))>=8 and regexp_replace(coalesce(phone,''),'\D','','g')=regexp_replace(p,'\D','','g')) limit 1 $$;

-- حماية المنتجات: حد الباقة + ملء اسم/تليفون التاجر + منع خصم غلط
create or replace function public.products_guard() returns trigger language plpgsql security definer set search_path=public as $$
declare m public.merchants; c int;
begin
  if new.merchant_id is not null then
    select * into m from public.merchants where id=new.merchant_id;
    if m.id is null then raise exception 'تاجر غير موجود'; end if;
    new.merchant_name:=m.name; new.seller:=m.name; new.merchant_phone:=m.phone;
    if tg_op='INSERT' and not public.is_admin() then
      if not m.is_active then raise exception 'حساب البائع موقوف'; end if;
      if m.plan_end is not null and m.plan_end<now() then raise exception 'الباقة منتهية، جدّد اشتراكك'; end if;
      select count(*) into c from public.products where merchant_id=new.merchant_id;
      if c>=public.plan_limit(m.plan) then raise exception 'وصلت للحد الأقصى لمنتجات باقتك'; end if;
    end if;
  end if;
  if new.old_price is not null and new.old_price<=new.price then new.old_price:=null; end if;
  return new;
end $$;
drop trigger if exists products_guard_t on public.products;
create trigger products_guard_t before insert or update on public.products for each row execute function public.products_guard();

-- تسجيل الطلب (الأسعار بتتاخد من قاعدة البيانات مش من المتصفح)
create or replace function public.place_order(p_name text,p_phone text,p_address text,p_note text,p_ship numeric,p_items jsonb)
returns bigint language plpgsql security definer set search_path=public as $$
declare oid bigint; it jsonb; pr public.products; q int; tot numeric:=0; n int:=0;
begin
  if (select count(*) from public.shop_orders where phone=left(coalesce(p_phone,''),20) and created_at>now()-interval '1 hour')>=5 then raise exception 'طلبات كتير في وقت قصير'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>50 then raise exception 'سلة غير صالحة'; end if;
  insert into public.shop_orders(name,phone,address,note,shipping) values(left(coalesce(p_name,''),100),left(coalesce(p_phone,''),20),left(coalesce(p_address,''),300),left(coalesce(p_note,''),300),least(greatest(coalesce(p_ship,0),0),500)) returning id into oid;
  for it in select * from jsonb_array_elements(p_items) loop
    select * into pr from public.products where id=(it->>'id')::bigint;
    if pr.id is null or not public.merchant_visible(pr.merchant_id) then continue; end if;
    q:=least(greatest(coalesce((it->>'qty')::int,1),1),100);
    insert into public.shop_order_items(order_id,product_id,merchant_id,name,price,qty,is_digital) values(oid,pr.id,pr.merchant_id,pr.name,pr.price,q,pr.is_digital);
    tot:=tot+pr.price*q; n:=n+1;
  end loop;
  if n=0 then raise exception 'مفيش منتجات صالحة'; end if;
  update public.shop_orders set total=tot+shipping where id=oid;
  return oid;
end $$;
grant execute on function public.place_order(text,text,text,text,numeric,jsonb), public.login_email(text) to anon, authenticated;

